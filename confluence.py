import os, requests, chromadb, re

def get_secret(key):
    try:
        import streamlit as st
        return st.secrets.get(key) or os.getenv(key)
    except: return os.getenv(key)

CONF_URL   = get_secret("CONFLUENCE_URL")
CONF_EMAIL = get_secret("CONFLUENCE_EMAIL")
CONF_TOKEN = get_secret("CONFLUENCE_TOKEN")
CONF_SPACE = get_secret("CONFLUENCE_SPACE") or "ITKB"
CONF_AUTH  = (CONF_EMAIL, CONF_TOKEN)
CONF_HEADS = {"Accept": "application/json"}

def strip_html(html):
    text = re.sub(r"<[^>]+>", " ", html)
    return re.sub(r"\s+", " ", text).strip()

def get_space_pages():
    r = requests.get(
        f"{CONF_URL}/wiki/rest/api/content",
        params={"spaceKey": CONF_SPACE,
                "expand": "body.storage,title", "limit": 50},
        auth=CONF_AUTH, headers=CONF_HEADS, timeout=10
    )
    r.raise_for_status()
    return r.json()["results"]

def ingest_confluence_to_chromadb() -> int:
    pages = get_space_pages()
    client = chromadb.PersistentClient(path="./chroma_db")
    try: client.delete_collection("it_kb")
    except: pass
    collection = client.create_collection("it_kb")
    docs, ids, metas = [], [], []
    for page in pages:
        title = page["title"]
        body  = strip_html(page["body"]["storage"]["value"])
        docs.append(f"# {title}\n\n{body}")
        ids.append(page["id"])
        metas.append({"title": title,
                      "url": f"{CONF_URL}/wiki/spaces/{CONF_SPACE}/pages/{page['id']}"})
        print(f"  Ingested: {title}")
    collection.add(documents=docs, ids=ids, metadatas=metas)
    return len(docs)

def confluence_status():
    if not all([CONF_URL, CONF_EMAIL, CONF_TOKEN]):
        return {"connected": False, "reason": "CONFLUENCE_* vars not set"}
    try:
        r = requests.get(f"{CONF_URL}/wiki/rest/api/space/{CONF_SPACE}",
                         auth=CONF_AUTH, headers=CONF_HEADS, timeout=5)
        return {"connected": r.status_code == 200,
                "space": CONF_SPACE, "url": CONF_URL}
    except Exception as e:
        return {"connected": False, "reason": str(e)}

def create_kb_article(title, issue, steps, resolution):
    """Write a resolved ticket back to Confluence as a new KB page."""
    steps_html = "".join(f"<li>{step}</li>" for step in steps)
    body = (f"<h2>Issue</h2><p>{issue}</p>"
            f"<h2>Steps tried</h2><ul>{steps_html}</ul>"
            f"<h2>Resolution</h2><p>{resolution}</p>"
            "<p>Auto-generated by AI IT Help Desk.</p>")
    r = requests.post(
        f"{CONF_URL}/wiki/rest/api/content",
        json={"type": "page", "title": title,
              "space": {"key": CONF_SPACE},
              "body": {"storage": {"value": body,
                                   "representation": "storage"}}},
        auth=CONF_AUTH,
        headers={**CONF_HEADS, "Content-Type": "application/json"},
        timeout=10
    )
    return r.json().get("id")